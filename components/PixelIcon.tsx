export function PixelIcon({
  name,
  size = 40,
  className,
}: {
  name: IconName;
  size?: number;
  className?: string;
}) {
  const def = ICONS[name];
  const grid = def.rows.length;
  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${grid} ${grid}`}
      shapeRendering="crispEdges"
      aria-hidden
      className={className}
    >
      {def.rows.flatMap((row, y) =>
        [...row].map((ch, x) =>
          ch === "." ? null : (
            <rect
              key={`${x}-${y}`}
              x={x}
              y={y}
              width="1"
              height="1"
              fill={def.colors[ch]}
            />
          )
        )
      )}
    </svg>
  );
}
